  static const Map<String, Map<String, String>> tables = {'en': en, 'tr': tr};

  static String get(String languageCode, String key, [Map<String, Object>? args]) {
    final table = tables[languageCode] ?? en;
    var value = table[key] ?? en[key] ?? key;
    if (args != null) {
      for (final entry in args.entries) {
        value = value.replaceAll('{${entry.key}}', '${entry.value}');
      }
    }
    return value;
  }
